import {
  isTourBlockChild,
  tourStories,
} from "gps-plus-slam-app-framework/ar/tour-story";
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import {
  BlobReader,
  TextWriter,
  Uint8ArrayWriter,
  ZipReader,
} from "@zip.js/zip.js";
import { describe, expect, it } from "vitest";

import {
  parseTourManifest,
  serializeTourManifest,
} from "gps-plus-slam-app-framework/ar/tour-manifest";
import {
  checkGlbInert,
  checkImageWithinCap,
  tourMediaTypeOfEntry,
} from "gps-plus-slam-app-framework/ar/tour-media";
import { drawnHeightM } from "gps-plus-slam-globe/editor";
import { egm96Geoid } from "gps-plus-slam-osm/elevation/egm96";

// Why these tests matter: the sample tour (owner decision S-D9) is the
// owner's first phone test of stations before in-app authoring exists. It is
// generated by scripts/build-sample-tour.mjs and committed under public/, so
// nothing else checks it: a broken asset or an invalid tour.json would only
// show on the phone, at Marienplatz or after a relocation. These tests read
// the committed file through the same parsers and checks the viewer uses.

const ZIP = fileURLToPath(
  new URL("../public/samples/marienplatz-tour.zip", import.meta.url),
);

async function entries(): Promise<Map<string, Uint8Array>> {
  const reader = new ZipReader(new BlobReader(new Blob([readFileSync(ZIP)])));
  const out = new Map<string, Uint8Array>();
  for (const entry of await reader.getEntries()) {
    if (entry.directory || entry.getData === undefined) continue;
    out.set(entry.filename, await entry.getData(new Uint8ArrayWriter()));
  }
  await reader.close();
  return out;
}

const M_PER_DEG = 111_320;
function metres(
  a: { lat: number; lon: number },
  b: { lat: number; lon: number },
): number {
  const cos = Math.cos(((a.lat + b.lat) / 2) * (Math.PI / 180));
  return Math.hypot(
    (b.lat - a.lat) * M_PER_DEG,
    (b.lon - a.lon) * M_PER_DEG * cos,
  );
}

describe("the sample tour (public/samples/marienplatz-tour.zip)", () => {
  it("is a valid version 4 tour with three geo stations in a fixed order", async () => {
    const files = await entries();
    const raw = files.get("tour.json");
    expect(raw).toBeDefined();
    const json = JSON.parse(new TextDecoder().decode(raw)) as unknown;
    // Written at version 4: an older build refuses it with "update the
    // app" rather than misreading it.
    expect(json).toMatchObject({ version: 5, minor: 0 });
    const manifest = parseTourManifest(json);
    expect(manifest.order).toBe("fixed");
    expect(manifest.stations.map((s) => s.id)).toEqual([
      "column",
      "gate",
      "steps",
    ]);
    for (const station of manifest.stations) {
      expect(station.geo).toBeDefined();
      expect(tourStories(station).length).toBeGreaterThan(0);
    }
  });

  // Why: a tester on the preview needs a station with a choice of stories
  // to meet the picker at all, and only the gate offers one; the column and
  // the steps keep one story so the plain flow stays visible too.
  it("offers two stories at the gate, one at the other stations", async () => {
    const files = await entries();
    const manifest = parseTourManifest(
      JSON.parse(new TextDecoder().decode(files.get("tour.json"))) as unknown,
    );
    expect(
      manifest.stations.map((s) => tourStories(s).map((t) => t.title)),
    ).toEqual([
      ["Sir Konrad's welcome"],
      ["The old gate", "The toll"],
      ["Farewell"],
    ]);
  });

  // Why: the sample is what a new author learns the format from, and with
  // stories alone it read as if everything had to live in one. A free item
  // needs a world view and a pose beside the stage, so the figure and the
  // item never stand in one spot.
  it("leaves free items at every station, each beside the stage", async () => {
    const files = await entries();
    const manifest = parseTourManifest(
      JSON.parse(new TextDecoder().decode(files.get("tour.json"))) as unknown,
    );
    const free = manifest.stations.map((s) =>
      s.children.filter(isTourBlockChild),
    );
    expect(free.map((f) => f.map((c) => [c.kind, c.view]))).toEqual([
      [
        ["shortText", "pin"],
        ["character", "speak"],
        ["character", "bubble"],
        ["audio", "spot"],
      ],
      [
        ["longText", "lectern"],
        ["audio", "zone"],
      ],
      [["shortText", "pin"]],
    ]);
    for (const item of free.flat()) {
      const [x, , z] = item.pose.position;
      expect(Math.hypot(x, z), item.id).toBeGreaterThan(2);
    }
  });

  it("places its stations 20-40 m apart at Marienplatz, so each can be found on its own", async () => {
    const files = await entries();
    const manifest = parseTourManifest(
      JSON.parse(new TextDecoder().decode(files.get("tour.json"))) as unknown,
    );
    const geos = manifest.stations.map((s) => s.geo);
    // The column of Marienplatz, Munich (a public place, S-D9).
    expect(metres(geos[0]!, { lat: 48.137393, lon: 11.575493 })).toBeLessThan(
      1,
    );
    for (let i = 0; i < geos.length; i += 1) {
      for (let j = i + 1; j < geos.length; j += 1) {
        const d = metres(geos[i]!, geos[j]!);
        // Apart by more than two found radii (5 m floor), close enough to walk.
        expect(d).toBeGreaterThan(20);
        expect(d).toBeLessThan(40);
      }
    }
  });

  // Why: a station's `alt` is ellipsoidal (a phone's GPS height); the 3D
  // view draws it at alt - N over a relief of orthometric heights. Written
  // as 519 m (about the square's height above sea level), every station
  // stood about 45 m under the drawn ground. The ground below is measured
  // independently of the 3D view: Mapterhorn's z14 tile 14/8718/5685
  // (fetched 2026-10-22), Terrarium-decoded and read bilinearly between
  // pixel centres at each station (the design system's globe lab drew
  // 515.9 m at the column on the same data). The tolerance is swept: the
  // verdict holds from 0.5 m to 2 m.
  it.each([0.5, 1, 2])(
    "stands each station within %s m of the ground the 3D view draws",
    async (toleranceM) => {
      const files = await entries();
      const manifest = parseTourManifest(
        JSON.parse(new TextDecoder().decode(files.get("tour.json"))) as unknown,
      );
      const groundM: Record<string, number> = {
        column: 515.83,
        gate: 514.17,
        steps: 516.23,
      };
      const geoid = egm96Geoid();
      for (const station of manifest.stations) {
        const geo = station.geo;
        const drawn = drawnHeightM(
          geo.alt,
          { lat: geo.lat, lng: geo.lon },
          geoid,
        );
        expect(Math.abs(drawn - groundM[station.id]!), station.id).toBeLessThan(
          toleranceM,
        );
      }
    },
  );

  it("carries every asset it names, each allowed, capped and inert", async () => {
    const files = await entries();
    const manifest = parseTourManifest(
      JSON.parse(new TextDecoder().decode(files.get("tour.json"))) as unknown,
    );
    for (const asset of manifest.assets) {
      const bytes = files.get(asset.path);
      expect(bytes, asset.path).toBeDefined();
      expect(tourMediaTypeOfEntry(asset.path), asset.path).not.toBeNull();
    }
    expect(checkImageWithinCap(files.get("content/knight.png")!)).toEqual({
      ok: true,
    });
    expect(checkGlbInert(files.get("content/arch.glb")!)).toEqual({ ok: true });
  });

  // Why: the sample is where a free sound is first heard on a phone - a
  // narration circle at the column (played on a tap, its transcript the
  // card's sentences) and a market zone at the gate (heard by itself). Both
  // files are generated (nothing to license), WAV, and small enough to
  // fetch over a phone's connection.
  it("carries a narration and an ambient sound, each a small generated WAV", async () => {
    const files = await entries();
    const manifest = parseTourManifest(
      JSON.parse(new TextDecoder().decode(files.get("tour.json"))) as unknown,
    );
    const sounds = manifest.stations
      .flatMap((s) => s.children)
      .flatMap((c) => (c.kind === "audio" ? [c] : []));
    expect(sounds.map((s) => [s.id, s.view])).toEqual([
      ["column-voice", "spot"],
      ["market-sound", "zone"],
    ]);
    const [voice, market] = sounds;
    expect(voice?.radiusM).toBe(6);
    expect(voice?.transcript?.split(". ").length).toBeGreaterThan(1);
    expect(market).toMatchObject({ maxM: 20, minM: 4, volume: 0.5 });
    for (const sound of sounds) {
      const path = manifest.assets.find((a) => a.id === sound.audio)?.path;
      const bytes = files.get(path ?? "");
      expect(path).toMatch(/\.wav$/);
      expect(new TextDecoder().decode(bytes?.slice(0, 4))).toBe("RIFF");
      expect(bytes?.length ?? Infinity).toBeLessThan(400_000);
    }
  });

  it("stores its entries uncompressed, so a visitor can stream them", async () => {
    const reader = new ZipReader(new BlobReader(new Blob([readFileSync(ZIP)])));
    const list = await reader.getEntries();
    await reader.close();
    for (const entry of list) {
      expect(entry.compressedSize, entry.filename).toBe(entry.uncompressedSize);
    }
    // TextWriter keeps the import honest for a text entry read.
    expect(TextWriter).toBeDefined();
  });

  it("is written back by today's writer to exactly the recorded bytes", async () => {
    // Why: the editor re-saves a tour it opened through this writer. A
    // change to the reader's in-memory model (a renamed field, a reshaped
    // type) must not change one written byte; this pins the writer's
    // output for a real tour, beside the generated ones in the framework.
    // Re-recorded when the tour moved to format 5 (its script writes it
    // through this writer, so the file is the writer's own bytes), and
    // when it gained the toll story and its free items (content only), and
    // two characters standing free, and a narration circle and a market
    // zone (content only), and when every story became a folder with the
    // story role (four stories, one `role` line each: 112 bytes), and when
    // the stage view was retired (the knight speaks 1 m off each spot,
    // facing the visitor's approach; the arch is placed at its own size).
    const files = await entries();
    const json = JSON.parse(
      new TextDecoder().decode(files.get("tour.json")),
    ) as unknown;
    const written = serializeTourManifest(parseTourManifest(json));
    expect(written).toBe(new TextDecoder().decode(files.get("tour.json")));
    expect(written.length).toBe(10902);
    expect(createHash("sha256").update(written).digest("hex")).toBe(
      "17a40e9387b5379e20dd6a97d8a50d20436849b604cd3a1026eb4cada3999007",
    );
  });
});
